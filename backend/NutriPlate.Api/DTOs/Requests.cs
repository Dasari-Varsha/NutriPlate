using System.ComponentModel.DataAnnotations;
namespace NutriPlate.Api.DTOs;
public record RegisterRequest([Required,EmailAddress] string Email,[Required,MinLength(8)] string Password,[Required,MinLength(2),MaxLength(80)] string DisplayName);
public record LoginRequest([Required,EmailAddress] string Email,[Required] string Password);
public record CreatePlanRequest([Required,MinLength(2),MaxLength(100)] string Name,[Required] string StartDate,[Required] string EndDate);
public record AddMealRequest([Required] string RecipeId,[Required] string Date,[Required] string MealType,[Range(1,20)] int Servings);
public record GenerateGroceryRequest([Required] string MealPlanId);
public record AddGroceryItemRequest([Required,MinLength(1),MaxLength(100)] string Name,[Range(0.1,100000)] double Quantity,[Required,MaxLength(30)] string Unit);
public record ToggleGroceryRequest(bool Purchased);
public record UpdateProfileRequest([Required,MinLength(2),MaxLength(80)] string DisplayName,List<string>? DietaryPreferences,List<string>? FoodRestrictions);
